-- 分割払いの「入金のされ方」を記録する。
--   クレジットカードの分割は、お客様がカード会社へ毎月払うだけで、
--   当社にはカード会社から契約月に全額がまとめて振り込まれる（ショット入金）。
--   一方、口座振替・銀行振込の分割は毎月その回ぶんが入ってくる。
--   歩合は入金ベースで計上するため、この違いを持たないと計上月がずれる。
--
--   hp_first_lump / hp_later_lump
--     true  … その区間はショット入金（区間の初月に区間の合計額が入る）
--     false … その区間は毎月入金
--     null  … 支払方法から自動判定（クレジットカード＝ショット、それ以外＝毎月）
-- 冪等: IF NOT EXISTS。
-- ============================================================
ALTER TABLE visit_reports ADD COLUMN IF NOT EXISTS hp_first_lump BOOLEAN;
ALTER TABLE visit_reports ADD COLUMN IF NOT EXISTS hp_later_lump BOOLEAN;
