-- ============================================================
-- アポの優先度（S / A / B / C）。アポ登録・訪問予定の編集の両方から設定する。
--   S=最優先 / A=高 / B=標準 / C=低。未設定(NULL)は従来どおり優先度なし。
-- 案件(cases.priority)の「高/中/低」とは別軸なので、アポ側に独立した列を持つ。
-- 冪等: IF NOT EXISTS。
-- ============================================================
ALTER TABLE appointments ADD COLUMN IF NOT EXISTS priority TEXT;  -- 'S' | 'A' | 'B' | 'C' | NULL
