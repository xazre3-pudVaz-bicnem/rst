-- 月給者の欠勤控除（ノーワーク・ノーペイ）に必要な列。
--   これまで欠勤日数は記録するだけで基本給を減額しておらず、月給者は欠勤しても満額支給＝過大払いだった。
--   日割単価の分母（月平均所定労働日数）は就業規則ごとに違うため、従業員ごとに保持する。
--   未設定(NULL)の従業員は従来どおり控除しない＝勝手に給与を減らさない。設定した月から適用される。
-- 冪等: IF NOT EXISTS。
-- ============================================================
ALTER TABLE employees ADD COLUMN IF NOT EXISTS monthly_work_days NUMERIC;   -- 月平均所定労働日数（日割の分母。例: 21）
ALTER TABLE payslips  ADD COLUMN IF NOT EXISTS absent_deduction NUMERIC DEFAULT 0;  -- 欠勤控除額（基本給から差引済みの内訳表示用）
